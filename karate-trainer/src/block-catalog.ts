export const BLOCKS: BlockDef[] = TABLE.map(([id, name, at, cubes], i) => ({
  id,
  name,
  at,
  cubes,
  src: `/images/blocks/block-${String(i + 1).padStart(2, "0")}.webp`,
}));

export function blockById(id: string): BlockDef | undefined {
  return BLOCKS.find((b) => b.id === id);
}
