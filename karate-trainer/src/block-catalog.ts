// 🧊 ブロック — アイテムタブで集める絵。**ブロックの少ない絵から順に開く。**
//
// いちばん最初は 3こ の絵。最後は 60こ をこえる大きな絵で、そこまでの
// 30まい。開くのは **稽古1回につき 多くても1つ**、そして回を重ねるほど
// 間があく（1・3・5・10・15・25・40・55・65回め … そのあとは 15回ごと）。
// 大きな絵ほど あとに来るので、「だんだん手に入りにくくなる」が
// 絵の大きさと そのまま重なる。
//
// 絵は `public/images/blocks/block-01.webp` … `block-30.webp`。
// 名前に「空手」「ピアノ」は入れない —— どちらのアプリでも同じものを集める。

export interface BlockDef {
  /// 保存に出てくる id。絵を入れ替えても番号は変えないこと。
  id: string;
  /// 子どもが読める名前。
  name: string;
  /// 絵の場所。
  src: string;
  /// 何回めの稽古で開くか。
  at: number;
  /// だいたい何このブロックでできているか（画面の小さな字に出す）。
  cubes: number;
}

